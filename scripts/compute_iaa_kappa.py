#!/usr/bin/env python3
"""Compute Cohen's κ for gold/real_bench dual annotations (A1 vs A2).

Reads ``gold/real_bench/<locale>.jsonl`` rows with fields
``path,line,span,label,source_lang,suggestion,annotator``.

Pairs rows that share ``(path, line, span)`` across annotators A1 and A2.
Writes a Markdown summary to stdout and optionally refreshes the κ section
in ``docs/real-benchmark.md``.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
GOLD_DIR = ROOT / "gold" / "real_bench"
DOCS_PATH = ROOT / "docs" / "real-benchmark.md"
LOCALES = ("en", "de", "es", "pl", "ru", "sv", "uk")


def load_rows(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def pair_key(row: dict[str, Any]) -> tuple[str, int, str]:
    return (str(row["path"]), int(row["line"]), str(row["span"]))


def cohen_kappa(labels_a: list[str], labels_b: list[str]) -> dict[str, float | int]:
    if len(labels_a) != len(labels_b):
        raise ValueError("annotator label lists must be the same length")
    n = len(labels_a)
    if n == 0:
        return {"n": 0, "po": 0.0, "pe": 0.0, "kappa": 0.0}
    agree = sum(1 for a, b in zip(labels_a, labels_b, strict=True) if a == b)
    po = agree / n
    cats = sorted(set(labels_a) | set(labels_b))
    ca = Counter(labels_a)
    cb = Counter(labels_b)
    pe = sum((ca[c] / n) * (cb[c] / n) for c in cats)
    kappa = 1.0 if pe == 1.0 else (po - pe) / (1.0 - pe)
    return {"n": n, "po": po, "pe": pe, "kappa": kappa}


def compute_locale(path: Path) -> dict[str, Any]:
    rows = load_rows(path)
    by_ann: dict[str, dict[tuple[str, int, str], dict[str, Any]]] = {"A1": {}, "A2": {}}
    for row in rows:
        ann = str(row.get("annotator", ""))
        if ann not in by_ann:
            continue
        by_ann[ann][pair_key(row)] = row
    shared = sorted(set(by_ann["A1"]) & set(by_ann["A2"]))
    labels_a = [by_ann["A1"][k]["label"] for k in shared]
    labels_b = [by_ann["A2"][k]["label"] for k in shared]
    stats = cohen_kappa(labels_a, labels_b)
    return {
        "locale": path.stem,
        "rows_total": len(rows),
        "paired": stats["n"],
        "po": round(float(stats["po"]), 4),
        "pe": round(float(stats["pe"]), 4),
        "kappa": round(float(stats["kappa"]), 4),
    }


def render_docs(results: list[dict[str, Any]], overall: dict[str, Any]) -> str:
    lines = [
        "# Real benchmark · annotator agreement",
        "",
        "Gold format: `gold/real_bench/<locale>.jsonl` with fields",
        "`path`, `line`, `span`, `label`, `source_lang`, `suggestion`, `annotator`.",
        "",
        "Annotators `A1` and `A2` label the same spans independently. Agreement is",
        "Cohen's κ on paired `(path, line, span)` keys.",
        "",
        "## Cohen's κ by locale",
        "",
        "| Locale | paired spans | P(o) | P(e) | κ |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in results:
        lines.append(
            f"| {row['locale']} | {row['paired']} | {row['po']:.3f} | "
            f"{row['pe']:.3f} | {row['kappa']:.3f} |"
        )
    lines.extend(
        [
            "",
            f"**Overall κ** (pooled pairs): **{overall['kappa']:.3f}** "
            f"(n={overall['n']}, P(o)={overall['po']:.3f}, P(e)={overall['pe']:.3f}).",
            "",
            "Gate for Stage V2-4: κ ≥ 0.70.",
            "",
            "Clean FPR tables live in `eval/real-benchmark.md` (regenerated by",
            "`scripts/build_real_benchmark.py --stage measure`).",
            "",
            "Provenance / licenses: `eval/corpora/manifest.json`, `LICENSE-THIRD-PARTY.md`.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--min-kappa",
        type=float,
        default=0.70,
        help="Fail with exit 1 if overall κ is below this threshold.",
    )
    parser.add_argument(
        "--write-docs",
        action="store_true",
        help=f"Refresh {DOCS_PATH.relative_to(ROOT)}",
    )
    parser.add_argument(
        "--gold-dir",
        type=Path,
        default=GOLD_DIR,
    )
    args = parser.parse_args()

    results: list[dict[str, Any]] = []
    all_a: list[str] = []
    all_b: list[str] = []
    for locale in LOCALES:
        path = args.gold_dir / f"{locale}.jsonl"
        if not path.is_file():
            continue
        rows = load_rows(path)
        by_ann: dict[str, dict[tuple[str, int, str], dict[str, Any]]] = {
            "A1": {},
            "A2": {},
        }
        for row in rows:
            ann = str(row.get("annotator", ""))
            if ann in by_ann:
                by_ann[ann][pair_key(row)] = row
        shared = sorted(set(by_ann["A1"]) & set(by_ann["A2"]))
        labels_a = [by_ann["A1"][k]["label"] for k in shared]
        labels_b = [by_ann["A2"][k]["label"] for k in shared]
        all_a.extend(labels_a)
        all_b.extend(labels_b)
        stats = cohen_kappa(labels_a, labels_b)
        results.append(
            {
                "locale": locale,
                "paired": stats["n"],
                "po": float(stats["po"]),
                "pe": float(stats["pe"]),
                "kappa": float(stats["kappa"]),
            }
        )

    if not results:
        print("error: no gold/real_bench/*.jsonl found", file=sys.stderr)
        return 2

    overall_stats = cohen_kappa(all_a, all_b)
    overall = {
        "n": int(overall_stats["n"]),
        "po": float(overall_stats["po"]),
        "pe": float(overall_stats["pe"]),
        "kappa": float(overall_stats["kappa"]),
    }

    for row in results:
        print(
            f"{row['locale']}: n={row['paired']} po={row['po']:.3f} "
            f"pe={row['pe']:.3f} kappa={row['kappa']:.3f}"
        )
    print(
        f"OVERALL: n={overall['n']} po={overall['po']:.3f} "
        f"pe={overall['pe']:.3f} kappa={overall['kappa']:.3f}"
    )

    if args.write_docs:
        DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)
        DOCS_PATH.write_text(render_docs(results, overall), encoding="utf-8")
        print(f"wrote {DOCS_PATH}")

    if overall["kappa"] < args.min_kappa:
        print(
            f"error: overall kappa {overall['kappa']:.3f} < min {args.min_kappa}",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
